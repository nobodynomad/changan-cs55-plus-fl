let currentLanguage = "uz";

function updateLanguage(language) {
  currentLanguage = copy[language] ? language : "uz";
  const languageCopy = copy[currentLanguage];

  document.documentElement.lang = currentLanguage;
  document.title = languageCopy.pageTitle;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = languageCopy[element.dataset.i18n];
    if (typeof value === "string") element.textContent = value;
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.placeholder = languageCopy[element.dataset.i18nPlaceholder];
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    element.alt = languageCopy[element.dataset.i18nAlt];
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    element.setAttribute("aria-label", languageCopy[element.dataset.i18nAria]);
  });

  const regionSelect = document.querySelector('select[name="region"]');
  if (regionSelect) {
    const previousValue = regionSelect.value;
    regionSelect.replaceChildren();
    const placeholder = document.createElement("option");
    placeholder.value = "";
    placeholder.disabled = true;
    placeholder.selected = true;
    placeholder.textContent = languageCopy.regionPlaceholder;
    regionSelect.append(placeholder);
    languageCopy.regionNames.forEach((region, index) => {
      const option = document.createElement("option");
      option.value = `region-${index + 1}`;
      option.textContent = region;
      regionSelect.append(option);
    });
    if (previousValue) regionSelect.value = previousValue;
  }

  document.querySelectorAll("[data-lang]").forEach((button) => {
    const active = button.dataset.lang === currentLanguage;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
  });
}

document.querySelectorAll("[data-lang]").forEach((button) => {
  button.addEventListener("click", () => updateLanguage(button.dataset.lang));
});

document.querySelectorAll("[data-scroll-form]").forEach((button) => {
  button.addEventListener("click", () => {
    document.querySelector("#request-form")?.scrollIntoView({ behavior: "smooth", block: "start" });
  });
});

const heroAction = document.querySelector(".hero-action");
const heroSection = document.querySelector(".hero");
const stickyCta = document.querySelector(".sticky-cta");
const requestSection = document.querySelector(".request-section");
const themeColorMeta = document.querySelector('meta[name="theme-color"]');

function updateBrowserChromeColor() {
  const heroBounds = heroSection?.getBoundingClientRect();
  const requestBounds = requestSection?.getBoundingClientRect();
  const isHeroVisible = Boolean(
    heroBounds && heroBounds.top < window.innerHeight * 0.2 && heroBounds.bottom > window.innerHeight * 0.8,
  );
  const isRequestVisible = Boolean(
    requestBounds && requestBounds.top < window.innerHeight * 0.8 && requestBounds.bottom > window.innerHeight * 0.2,
  );
  const color = isRequestVisible ? "#0f1216" : isHeroVisible ? "#6b94bf" : "#f4f6f8";

  document.documentElement.style.setProperty("--browser-chrome-color", color);
  if (themeColorMeta && themeColorMeta.content !== color) themeColorMeta.content = color;
}

function updateStickyCta() {
  if (!heroAction || !stickyCta) return;

  const isPastHeroButton = heroAction.getBoundingClientRect().bottom <= 0;
  const stickyTop = window.innerHeight - stickyCta.offsetHeight;
  const requestBounds = requestSection?.getBoundingClientRect();
  const isOverDarkSection = Boolean(
    requestBounds && requestBounds.top < window.innerHeight && requestBounds.bottom > stickyTop,
  );

  stickyCta.classList.toggle("is-visible", isPastHeroButton);
  stickyCta.classList.toggle("is-on-dark", isOverDarkSection);
  stickyCta.setAttribute("aria-hidden", String(!isPastHeroButton));
  stickyCta.inert = !isPastHeroButton;
  stickyCta.querySelector("button").tabIndex = isPastHeroButton ? 0 : -1;
  document.body.classList.toggle("has-sticky-cta", isPastHeroButton);
  updateBrowserChromeColor();
}

window.addEventListener("scroll", updateStickyCta, { passive: true });
window.addEventListener("resize", updateStickyCta);
updateStickyCta();

const revealElements = document.querySelectorAll("[data-reveal]");
if ("IntersectionObserver" in window && !window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
  const revealObserver = new IntersectionObserver((entries, observer) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      entry.target.classList.add("is-visible");
      observer.unobserve(entry.target);
    });
  }, { threshold: 0.14, rootMargin: "0px 0px -36px 0px" });
  revealElements.forEach((element) => revealObserver.observe(element));
} else {
  revealElements.forEach((element) => element.classList.add("is-visible"));
}

